#include "tetris.h"
#include <string.h>

/* [type][rotation][cell][x,y] */
static const int SHAPES[TET_COUNT][4][4][2] = {
    /* I */
    { { {0,1},{1,1},{2,1},{3,1} }, { {2,0},{2,1},{2,2},{2,3} },
      { {0,2},{1,2},{2,2},{3,2} }, { {1,0},{1,1},{1,2},{1,3} } },
    /* O */
    { { {1,0},{2,0},{1,1},{2,1} }, { {1,0},{2,0},{1,1},{2,1} },
      { {1,0},{2,0},{1,1},{2,1} }, { {1,0},{2,0},{1,1},{2,1} } },
    /* T */
    { { {1,0},{0,1},{1,1},{2,1} }, { {1,0},{1,1},{2,1},{1,2} },
      { {0,1},{1,1},{2,1},{1,2} }, { {1,0},{0,1},{1,1},{1,2} } },
    /* S */
    { { {1,0},{2,0},{0,1},{1,1} }, { {1,0},{1,1},{2,1},{2,2} },
      { {1,1},{2,1},{0,2},{1,2} }, { {0,0},{0,1},{1,1},{1,2} } },
    /* Z */
    { { {0,0},{1,0},{1,1},{2,1} }, { {2,0},{1,1},{2,1},{1,2} },
      { {0,1},{1,1},{1,2},{2,2} }, { {1,0},{0,1},{1,1},{0,2} } },
    /* J */
    { { {0,0},{0,1},{1,1},{2,1} }, { {1,0},{2,0},{1,1},{1,2} },
      { {0,1},{1,1},{2,1},{2,2} }, { {1,0},{1,1},{0,2},{1,2} } },
    /* L */
    { { {2,0},{0,1},{1,1},{2,1} }, { {1,0},{1,1},{1,2},{2,2} },
      { {0,1},{1,1},{2,1},{0,2} }, { {0,0},{1,0},{1,1},{1,2} } },
};

void piece_spawn(Piece *p, TetType type) {
    p->type = type;
    p->rot  = 0;
    p->x    = (BOARD_W / 2) - 2;  /* roughly centered */
    p->y    = -HIDDEN_ROWS + 1;   /* start in hidden area for I-style shapes */
}

bool piece_cells(const Piece *p, int cells[4][2]) {
    for (int i = 0; i < 4; i++) {
        cells[i][0] = p->x + SHAPES[p->type][p->rot][i][0];
        cells[i][1] = p->y + SHAPES[p->type][p->rot][i][1];
    }
    return true;
}

void piece_rotate(Piece *p, int dir) {
    if (p->type == TET_O) return;
    p->rot = (p->rot + (dir > 0 ? 1 : 3)) & 3;
}